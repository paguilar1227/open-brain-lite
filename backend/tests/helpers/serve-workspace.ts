import { PGlite } from '@electric-sql/pglite';
import { vector } from '@electric-sql/pglite-pgvector';
import { uuid_ossp } from '@electric-sql/pglite/contrib/uuid_ossp';
import { readFile, readdir, mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { serve } from '@hono/node-server';
import { createApp } from '../../src/app.js';
import { StubEmbeddingProvider, StubLLMProvider } from '../../src/providers/stub.js';
import { LocalFileStorage } from '../../src/storage/local.js';
import type { DbClient } from '../../src/db/client.js';
import type { ServiceDeps } from '../../src/services/index.js';
if (process.env.OPEN_BRAIN_TEST_FIXTURE !== '1') throw new Error('This server is only for explicit isolated tests.');
const pg = new PGlite({ extensions: { vector, uuid_ossp } });
const query = async (sql: string, params?: unknown[]) => { const result = await pg.query(sql, params); return { ...result, rowCount: result.affectedRows ?? result.rows.length }; };
const db = { query, pool: { query }, transaction: (fn: any) => pg.transaction(tx => fn({ query: async (sql: string, params?: unknown[]) => { const result = await tx.query(sql, params); return { ...result, rowCount: result.affectedRows ?? result.rows.length }; } })) } as unknown as DbClient;
for (const file of (await readdir('migrations')).filter(file => file.endsWith('.sql')).sort()) await pg.exec(await readFile(join('migrations', file), 'utf8'));
const storage = await mkdtemp(join(tmpdir(), 'open-brain-workspace-'));
const deps = { db, config: { apiKey: '', llmProvider: 'stub', storageProvider: 'local' }, embeddingProvider: new StubEmbeddingProvider(), metadataLLM: new StubLLMProvider(), ragFastLLM: new StubLLMProvider(), blobStorage: new LocalFileStorage(storage, 'isolated-fixture-key') } as unknown as ServiceDeps;
const app = createApp(deps);
const server = serve({ fetch: app.fetch, hostname: '127.0.0.1', port: 0 }, info => console.log(JSON.stringify({ fixtureUrl: `http://127.0.0.1:${info.port}`, storage })));
process.on('SIGTERM', () => server.close(() => { void pg.close().then(() => process.exit()); }));
